import { describe, expect, it } from 'vitest'

import { buildEslintRoute, buildOxlintRoute } from '../__tests__/factories/inventory-factories.ts'
import { buildRulesetDefinition } from '../__tests__/factories/ruleset-definition-factories.ts'
import { oxlintSpellingsOf } from '../rule-id-parts.ts'
import { renderRuleIds, renderRulesetNames } from './render-generated.ts'

const GENERATED_HEADER = '// Generated by `bun run generate` (src/generate/run-generate.ts). Do not edit.'

describe('renderRuleIds', () => {
  it('lists each RuleId on a line of its own, in the order routing sorted them', () => {
    const routes = [
      buildEslintRoute('@typescript-eslint/no-floating-promises', {
        typed: true,
        shipped: null,
        oxlintSpellings: oxlintSpellingsOf('typescript/no-floating-promises'),
      }),
      buildOxlintRoute('import-x/no-cycle', {
        oxlintName: 'import/no-cycle',
        oxlintSpellings: oxlintSpellingsOf('import/no-cycle'),
        oxlintPlugin: 'import',
        eslintAliases: ['import/no-cycle'],
        shipped: null,
      }),
      buildEslintRoute('n/prefer-global/buffer', { typed: false, shipped: null, oxlintSpellings: [] }),
      buildOxlintRoute('no-debugger', {
        oxlintName: 'no-debugger',
        oxlintSpellings: oxlintSpellingsOf('no-debugger'),
        oxlintPlugin: 'eslint',
        eslintAliases: [],
        shipped: null,
      }),
    ]

    expect(renderRuleIds(routes)).toStrictEqual(
      `${GENERATED_HEADER}

export type RuleId =
  | "@typescript-eslint/no-floating-promises"
  | "import-x/no-cycle"
  | "n/prefer-global/buffer"
  | "no-debugger"
`,
    )
  })
})

describe('renderRulesetNames', () => {
  it("keeps the definitions' order in each list, grouping libs rulesets by domain in order of first appearance", () => {
    const definitions = [
      buildRulesetDefinition('type-safety', { list: 'quality', domain: null }),
      buildRulesetDefinition('correctness', { list: 'quality', domain: null }),
      buildRulesetDefinition('vitest', { list: 'libs', domain: 'testing' }),
      buildRulesetDefinition('react-hook-form', { list: 'libs', domain: 'forms' }),
      buildRulesetDefinition('storybook', { list: 'libs', domain: 'testing' }),
      buildRulesetDefinition('node', { list: 'runtimes', domain: null, env: 'node' }),
      buildRulesetDefinition('browser', { list: 'runtimes', domain: null, env: 'browser' }),
    ]

    expect(renderRulesetNames(definitions)).toStrictEqual(
      `${GENERATED_HEADER}

export type QualityRulesetName =
  | "type-safety"
  | "correctness"

export type LibsRulesets = {
  readonly "testing"?: readonly ("vitest" | "storybook")[]
  readonly "forms"?: readonly ("react-hook-form")[]
}

export type RuntimeRulesetName =
  | "node"
  | "browser"

export type LanguageRulesetName = never
`,
    )
  })

  it('throws on a libs ruleset without a domain, naming it', () => {
    const definitions = [
      buildRulesetDefinition('react', { list: 'libs', domain: 'ui' }),
      buildRulesetDefinition('vitest', { list: 'libs', domain: null }),
    ]

    expect(() => renderRulesetNames(definitions)).toThrow(/vitest/)
  })
})
