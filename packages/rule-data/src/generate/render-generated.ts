import type { RulesetDefinition, RulesetList } from '../catalog.ts'
import type { TurnedOnBy } from '../turned-on-by.ts'
import { groupBy } from './collections.ts'

/** What the rule-ID file reads of a route, as routing writes it or the catalog gives it: its ID, and what turns it on. */
type RouteTurnedOnBy = { readonly id: string; readonly shipped: TurnedOnBy | null }

const GENERATED_HEADER = '// Generated by `bun run generate` (src/generate/run-generate.ts). Do not edit.'
const JSON_INDENT = 2

export function renderJson(value: unknown): string {
  return `${JSON.stringify(value, null, JSON_INDENT)}\n`
}

export function renderRuleIds(routes: readonly RouteTurnedOnBy[]): string {
  return renderTypeFile([renderUnionType('RuleId', routes.map(({ id }) => id))])
}

/** `rule-ids.ts`: every RuleId, then the ones `allowSuppressions` decides, which a consumer cannot set in `rules`. */
export function renderRuleIdsFile(routes: readonly RouteTurnedOnBy[]): string {
  const suppressionRuleIds = routes.filter(isDecidedBySuppressions).map(({ id }) => id)
  return `${renderRuleIds(routes)}\n${renderUnionType('SuppressionRuleId', suppressionRuleIds)}\n`
}

function isDecidedBySuppressions({ shipped }: RouteTurnedOnBy): boolean {
  return shipped !== null && 'whenSuppressions' in shipped
}

export function renderRulesetNames(definitions: readonly RulesetDefinition[]): string {
  return renderTypeFile([
    renderUnionType('QualityRulesetName', namesIn(definitions, 'quality')),
    renderLibsRulesets(definitions),
    renderUnionType('RuntimeRulesetName', namesIn(definitions, 'runtimes')),
    renderUnionType('LanguageRulesetName', namesIn(definitions, 'languages')),
  ])
}

function renderTypeFile(declarations: readonly string[]): string {
  return `${[GENERATED_HEADER, ...declarations].join('\n\n')}\n`
}

/** One member per line, so a rule added or removed is a one-line diff. */
function renderUnionType(name: string, members: readonly string[]): string {
  if (members.length === 0) return `export type ${name} = never`
  return `export type ${name} =${members.map((member) => `\n  | ${literalOf(member)}`).join('')}`
}

/** Each domain may list only its own rulesets, and every domain is optional. */
function renderLibsRulesets(definitions: readonly RulesetDefinition[]): string {
  const libsByDomain = groupBy(definitionsIn(definitions, 'libs'), libsDomainOf)
  const fields = [...libsByDomain].map(([domain, libs]) => renderLibsDomainField(domain, libs))
  return `export type LibsRulesets = {\n${fields.join('\n')}\n}`
}

function renderLibsDomainField(domain: string, libs: readonly RulesetDefinition[]): string {
  const names = libs.map(({ name }) => literalOf(name))
  return `  readonly ${literalOf(domain)}?: readonly (${names.join(' | ')})[]`
}

function definitionsIn(definitions: readonly RulesetDefinition[], list: RulesetList): readonly RulesetDefinition[] {
  return definitions.filter((definition) => definition.list === list)
}

function namesIn(definitions: readonly RulesetDefinition[], list: RulesetList): readonly string[] {
  return definitionsIn(definitions, list).map(({ name }) => name)
}

function libsDomainOf({ name, domain }: RulesetDefinition): string {
  if (domain === null) throw new Error(`libs ruleset ${name} has no domain`)
  return domain
}

function literalOf(value: string): string {
  return JSON.stringify(value)
}
